/**
 * Converts the Figma variable export (tokens/figma-variables.json) into:
 *   - src/styles/tokens.css  → CSS custom properties named exactly like Figma's WEB code syntax
 *                              (primitives on :root, Theme collection per mode: Light / Dark)
 *   - src/styles/theme.css   → Tailwind v4 @theme mapping that exposes ONLY semantic tokens as utilities
 *                              (bg-surface, text-secondary, border-subtle, p-16, rounded-md, shadow-elevation-2, type-body…)
 *
 * Run with `npm run tokens` (Node ≥ 22.18 strips the types natively).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type Value = string | number;
interface Variable {
  type: 'COLOR' | 'FLOAT';
  values: Record<string, Value>;
}
interface Collection {
  modes: string[];
  variables: Record<string, Variable>;
}
interface TextStyle {
  family: string;
  weight: number;
  size: number;
  lineHeight: number;
  letterSpacing: number;
  textCase?: 'UPPER';
}
interface Shadow {
  x: number;
  y: number;
  blur: number;
  spread: number;
  color: string;
}
interface Export {
  source: { fileKey: string; exportedAt: string };
  collections: { Primitives: Collection; Theme: Collection };
  textStyles: Record<string, TextStyle>;
  effectStyles: Record<string, Shadow[]>;
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(readFileSync(resolve(root, 'tokens/figma-variables.json'), 'utf8')) as Export;
const { Primitives, Theme } = data.collections;

const slug = (name: string) => name.toLowerCase().replace(/[\s/]+/g, '-');
// Figma WEB code syntax: primitives → --stone-100, --space-8 · theme → --color-bg-surface
const primitiveVar = (name: string) => `--${slug(name)}`;
const themeVar = (name: string) => `--color-${slug(name)}`;
const isAlias = (v: Value): v is string => typeof v === 'string' && v.startsWith('{');
const aliasTarget = (v: string) => v.slice(1, -1);

const ref = (v: Value, unit = '') => {
  if (isAlias(v)) {
    const target = aliasTarget(v);
    return `var(${target in Theme.variables ? themeVar(target) : primitiveVar(target)})`;
  }
  return typeof v === 'number' ? `${v}${unit}` : v;
};

const header = `/* Generated by scripts/build-tokens.ts from tokens/figma-variables.json
 * Figma file ${data.source.fileKey} · exported ${data.source.exportedAt}
 * Do not edit by hand: re-export from Figma and run \`npm run tokens\`. */\n`;

/* ───────────────────────── tokens.css ───────────────────────── */
const primitives: string[] = [];
for (const [name, v] of Object.entries(Primitives.variables)) {
  // radius/* is emitted by Tailwind's @theme (same --radius-* names), see theme.css
  if (name.startsWith('radius/')) continue;
  primitives.push(`  ${primitiveVar(name)}: ${ref(v.values.Value, 'px')};`);
}

const themeBlock = (mode: string) =>
  Object.entries(Theme.variables)
    .map(([name, v]) => `  ${themeVar(name)}: ${ref(v.values[mode])};`)
    .join('\n');

const tokensCss = `${header}
:root {
${primitives.join('\n')}
}

:root,
[data-theme='light'] {
  color-scheme: light;
${themeBlock('Light')}
}

[data-theme='dark'] {
  color-scheme: dark;
${themeBlock('Dark')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${themeBlock('Dark').replace(/^/gm, '  ')}
  }
}
`;

/* ───────────────────────── theme.css ───────────────────────── */
// Semantic Theme token → Tailwind theme namespaces (utility prefixes)
function utilitiesFor(name: string): string[] {
  const [group, ...rest] = name.split('/');
  const key = rest.join('-');
  switch (group) {
    case 'bg':
      return [`--background-color-${key}`];
    case 'text':
      return [`--text-color-${key}`];
    case 'icon':
      return [`--text-color-icon-${key}`, `--fill-icon-${key}`, `--stroke-icon-${key}`];
    case 'border':
      return [
        `--border-color-${key}`,
        `--divide-color-${key}`,
        `--outline-color-${key}`,
        `--ring-color-${key}`,
      ];
    case 'status': {
      // status/good/solid → bg-good-solid · text-good-solid · border-good-solid
      // status/good/text  → text-good          status/good/border → border-good
      // status/good/border → border-good-subtle (pairs with bg-good-subtle; border-critical is border/critical)
      const [tone, kind] = rest;
      if (kind === 'text') return [`--text-color-${tone}`, `--fill-${tone}`, `--stroke-${tone}`];
      if (kind === 'border') return [`--border-color-${tone}-subtle`];
      if (kind === 'subtle') return [`--background-color-${tone}-subtle`];
      return [
        `--background-color-${tone}-solid`,
        `--text-color-${tone}-solid`,
        `--border-color-${tone}-solid`,
        `--fill-${tone}-solid`,
        `--stroke-${tone}-solid`,
      ];
    }
    case 'chart':
      return [
        `--background-color-chart-${key}`,
        `--text-color-chart-${key}`,
        `--border-color-chart-${key}`,
        `--fill-chart-${key}`,
        `--stroke-chart-${key}`,
      ];
    case 'focus':
      return [`--ring-color-focus-ring`];
    default:
      throw new Error(`No utility mapping for Theme variable "${name}"`);
  }
}

const seen = new Map<string, string>();
const colorTheme = Object.keys(Theme.variables)
  .flatMap((name) =>
    utilitiesFor(name).map((util) => {
      if (seen.has(util)) throw new Error(`${util} is produced by both ${seen.get(util)} and ${name}`);
      seen.set(util, name);
      return `  ${util}: var(${themeVar(name)});`;
    }),
  )
  .join('\n');

const spacing = Object.keys(Primitives.variables)
  .filter((n) => n.startsWith('space/'))
  .map((n) => `  --spacing-${n.split('/')[1]}: var(${primitiveVar(n)});`)
  .join('\n');

const radius = Object.entries(Primitives.variables)
  .filter(([n]) => n.startsWith('radius/'))
  .map(([n, v]) => `  --radius-${n.split('/')[1]}: ${v.values.Value}px;`)
  .join('\n');

const shadowValue = (layers: Shadow[]) =>
  layers.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${ref(s.color)}`).join(', ');
const shadows = Object.entries(data.effectStyles)
  .map(([name, layers]) => `  --shadow-${slug(name)}: ${shadowValue(layers)};`)
  .join('\n');

const fontStack = (family: string) =>
  family === 'Geist Mono'
    ? `'Geist Mono Variable', 'Geist Mono', ui-monospace, SFMono-Regular, Menlo, monospace`
    : `'Geist Variable', 'Geist', ui-sans-serif, system-ui, sans-serif`;

// "Caption/Default" → type-caption, "Body/Small Strong" → type-body-small-strong
const typeSlug = (name: string) => slug(name).replace(/-default$/, '');

const typeUtilities = Object.entries(data.textStyles)
  .map(([name, s]) => {
    const lines = [
      `  font-family: var(${s.family === 'Geist Mono' ? '--font-mono' : '--font-sans'});`,
      `  font-size: ${s.size}px;`,
      `  line-height: ${s.lineHeight}px;`,
      `  font-weight: ${s.weight};`,
      `  letter-spacing: ${+s.letterSpacing.toFixed(2)}px;`,
    ];
    if (s.textCase === 'UPPER') lines.push('  text-transform: uppercase;');
    return `/* ${name} */\n@utility type-${typeSlug(name)} {\n${lines.join('\n')}\n}`;
  })
  .join('\n\n');

const themeCss = `${header}
/* Tailwind's default palette, radii, shadows and type scale are removed on purpose:
 * components can only reach Watt's semantic tokens. */
@theme {
  --color-*: initial;
  --text-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;

  --font-sans: ${fontStack('Geist')};
  --font-mono: ${fontStack('Geist Mono')};

  /* radius/* — same names as Figma's code syntax (var(--radius-md)) */
${radius}
}

@theme inline {
  /* 1 spacing unit = 1px, so p-16 / gap-8 / h-36 read exactly like the Figma values.
   * Named steps map to the space/* tokens. */
  --spacing: 1px;
${spacing}

  /* Theme collection (Light / Dark) */
${colorTheme}

  /* Effect styles */
${shadows}
}

/* Text styles */
${typeUtilities}
`;

const out = (file: string, css: string) => {
  const path = resolve(root, file);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, css);
  console.log(`✔ ${file}`);
};
out('src/styles/tokens.css', tokensCss);
out('src/styles/theme.css', themeCss);
console.log(
  `  ${Object.keys(Primitives.variables).length} primitives · ${Object.keys(Theme.variables).length} theme tokens × ${Theme.modes.join('/')} · ${Object.keys(data.textStyles).length} text styles · ${Object.keys(data.effectStyles).length} effects`,
);
